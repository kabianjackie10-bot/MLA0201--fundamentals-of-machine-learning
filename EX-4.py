        "\n",
        "import numpy as np\n",
        "import matplotlib.pyplot as plt\n",
        "from sklearn.datasets import load_iris\n",
        "from sklearn.model_selection import train_test_split\n",
        "from sklearn.preprocessing import StandardScaler, OneHotEncoder\n",
        "from sklearn.metrics import accuracy_score, ConfusionMatrixDisplay\n",
        "\n",
        "# 1. Load and prepare the dataset\n",
        "iris = load_iris()\n",
        "X = iris.data\n",
        "y = iris.target\n",
        "\n",
        "scaler = StandardScaler()\n",
        "X = scaler.fit_transform(X)\n",
        "\n",
        "encoder = OneHotEncoder(sparse_output=False)\n",
        "Y = encoder.fit_transform(y.reshape(-1, 1))\n",
        "\n",
        "X_train, X_test, Y_train, Y_test, y_train, y_test = train_test_split(\n",
        "    X, Y, y, test_size=0.25, random_state=42, stratify=y\n",
        ")\n",
        "\n",
        "# 2. Initialize the neural network\n",
        "np.random.seed(42)\n",
        "input_size = X_train.shape[1]\n",
        "hidden_size = 8\n",
        "output_size = Y_train.shape[1]\n",
        "learning_rate = 0.05\n",
        "epochs = 1000\n",
        "\n",
        "W1 = np.random.randn(input_size, hidden_size) * 0.1\n",
        "b1 = np.zeros((1, hidden_size))\n",
        "W2 = np.random.randn(hidden_size, output_size) * 0.1\n",
        "b2 = np.zeros((1, output_size))\n",
        "\n",
        "def sigmoid(x):\n",
        "    return 1 / (1 + np.exp(-np.clip(x, -500, 500)))\n",
        "\n",
        "def softmax(x):\n",
        "    exp_x = np.exp(x - np.max(x, axis=1, keepdims=True))\n",
        "    return exp_x / np.sum(exp_x, axis=1, keepdims=True)\n",
        "\n",
        "# 3. Train using Backpropagation\n",
        "loss_history = []\n",
        "\n",
        "for epoch in range(epochs):\n",
        "    # Forward propagation\n",
        "    z1 = X_train @ W1 + b1\n",
        "    a1 = sigmoid(z1)\n",
        "    z2 = a1 @ W2 + b2\n",
        "    a2 = softmax(z2)\n",
        "\n",
        "    # Cross-entropy loss\n",
        "    loss = -np.mean(np.sum(\n",
        "        Y_train * np.log(a2 + 1e-9), axis=1\n",
        "    ))\n",
        "    loss_history.append(loss)\n",
        "\n",
        "    # Backward propagation\n",
        "    m = len(X_train)\n",
        "    dz2 = (a2 - Y_train) / m\n",
        "    dW2 = a1.T @ dz2\n",
        "    db2 = np.sum(dz2, axis=0, keepdims=True)\n",
        "\n",
        "    dz1 = (dz2 @ W2.T) * a1 * (1 - a1)\n",
        "    dW1 = X_train.T @ dz1\n",
        "    db1 = np.sum(dz1, axis=0, keepdims=True)\n",
        "\n",
        "    # Update weights and biases\n",
        "    W2 -= learning_rate * dW2\n",
        "    b2 -= learning_rate * db2\n",
        "    W1 -= learning_rate * dW1\n",
        "    b1 -= learning_rate * db1\n",
        "\n",
        "    if (epoch + 1) % 200 == 0:\n",
        "        print(f\"Epoch {epoch+1}, Loss: {loss:.4f}\")\n",
        "\n",
        "# 4. Test the trained network\n",
        "hidden = sigmoid(X_test @ W1 + b1)\n",
        "probabilities = softmax(hidden @ W2 + b2)\n",
        "predictions = np.argmax(probabilities, axis=1)\n",
        "\n",
        "accuracy = accuracy_score(y_test, predictions)\n",
        "print(f\"\\nTest Accuracy: {accuracy * 100:.2f}%\")\n",
        "\n",
        "print(\"\\nSample Predictions:\")\n",
        "for i in range(5):\n",
        "    print(\n",
        "        f\"Actual: {iris.target_names[y_test[i]]:10s} | \"\n",
        "        f\"Predicted: {iris.target_names[predictions[i]]}\"\n",
        "    )\n",
        "\n",
        "# 5. Plot training loss\n",
        "plt.figure(figsize=(8, 4))\n",
        "plt.plot(loss_history)\n",
        "plt.title(\"ANN Training Using Backpropagation\")\n",
        "plt.xlabel(\"Epoch\")\n",
        "plt.ylabel(\"Cross-Entropy Loss\")\n",
        "plt.grid(True)\n",
        "plt.show()\n",
        "\n",
        "# 6. Plot confusion matrix\n",
        "ConfusionMatrixDisplay.from_predictions(\n",
        "    y_test,\n",
        "    predictions,\n",
        "    display_labels=iris.target_names,\n",
        "    cmap=\"Blues\"\n",
        ")\n",
        "plt.title(\"ANN Classification - Confusion Matrix\")\n",
        "plt.tight_layout()\n",
